# config/triggers.py
# Markov 情境來源（γ）的關鍵字觸發字典
#
# 設計理念（認知科學佐證）：
#   Gibson (1979) Affordance Theory：
#     環境物件本身會「邀請」特定行動 — 看到杯子想喝、看到客人想服務
#   Schank & Abelson (1977) Script Theory：
#     人類用情境腳本處理日常，腳本由情境關鍵字觸發
#
# 用法：
#   markov_engine.situation_score() 掃描合併文字（scene + yolo_desc + 最近 STM）
#   每命中一個關鍵字 → 對應行動加分 KEYWORD_BOOST_PER_HIT
#   再用 softmax 正規化成機率分布，作為 γ（情境）來源
#
# 同時也存放：
#   - 情緒影響行動的對照（emotion → 加分）
#   - 對話拒絕的回應模板
#
# 對應 ARCHITECTURE.md §6.1.3
# ================================================================


