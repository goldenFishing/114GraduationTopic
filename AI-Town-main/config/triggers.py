# ================================================================
# E. 工具函式（給 markov_engine 直接呼叫用）
# ================================================================

def get_keyword_hits(text: str, action: str) -> int:
    """計算 text 中命中 action 的關鍵字次數。"""
    keywords = ACTION_KEYWORD_BOOST.get(action, [])
    return sum(1 for kw in keywords if kw in text)


def get_emotion_boost(emotion: str, action: str) -> float:
    """取得指定情緒對指定行動的加分。"""
    return EMOTION_TO_ACTION_BOOST.get(emotion, {}).get(action, 0.0)
